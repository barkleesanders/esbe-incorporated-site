#!/usr/bin/env python3
"""Apply the WebMCP discovery advertisement to the shipped bundle (index.js).

Deterministic, assertion-guarded string surgery, in the same idiom as
patch_webmcp.py / patch_ot.py. Input is the CURRENT shipped bundle -
the origin-trial bundle (221,553 chars, sha256 8e813315...; see
WEBMCP.md) - NOT an earlier build. Three transforms, nothing else:

  1. Head link: insert
       <link rel="webmcp" href="/.well-known/webmcp.json" type="application/json">
     immediately after the origin-trial <meta> in the <head> of all
     5 pages (/, /donate, /community, /privacy, /terms), alongside the
     token patch_ot.py placed there.

  2. llms.txt: /llms.txt is generated by the bundle (buildLlms) - there
     is no static llms.txt file. Append a "## WebMCP tools" section
     (the preference instruction + one line per registered tool, text
     copied from public/webmcp-tools.js) to buildLlms's output.

  3. robots.txt: /robots.txt is served from the public/robots.txt
     asset; buildRobots generates byte-identical content and both
     carry "keep in sync" headers. Append the canonical WebMCP
     comment block to buildRobots's output so the generated copy
     stays in sync with the asset (the asset is edited in the same
     change).

The catalogue itself ships as a static asset:
public/.well-known/webmcp.json.

Run: python3 patch_adv.py index.js > index.patched.js  (or in place with -i)
Re-running it on the OT bundle reproduces the advertisement bundle
byte-for-byte. It refuses (AssertionError) if any anchor count differs
from the shipped bundle's, or if the advertisement is already present.
"""
import json
import re
import sys

LINK = '<link rel="webmcp" href="/.well-known/webmcp.json" type="application/json">'
META_RE = re.compile(r'<meta http-equiv="origin-trial" content="[^"]+">')

# Tool inventory copied verbatim from public/webmcp-tools.js
# (name, description) - never paraphrased.
TOOLS = [
    ("get_page_guide", "List ESBE Incorporated's public pages (home, donate, community, privacy, terms) with each page's title, description, URL, and last-updated date, from the site's own page catalog."),
    ("search_site", "Search the full text of ESBE Incorporated's public pages (home, donate, community, privacy, terms) and return matching excerpts with the page each came from."),
    ("get_page", "Read one of ESBE Incorporated's public pages as markdown: /, /donate, /community, /privacy, or /terms. Returns the same markdown the site serves to agents at its .md URLs."),
    ("navigate_to_page", "Navigate the visitor's browser to one of ESBE Incorporated's public pages: home (/), donate (/donate), community (/community), privacy (/privacy), or terms (/terms). Only these internal paths are used."),
]

LLMS_INSTRUCTION = "This site registers WebMCP tools in the browser via document.modelContext. Agents that support WebMCP: prefer these tools over scraping HTML. Tool catalogue (JSON): /.well-known/webmcp.json"

ROBOTS_BLOCK = [
    "# WebMCP: this site offers in-browser agent tools via document.modelContext.",
    "# Agents that support WebMCP: prefer the registered tools over scraping HTML.",
    "# Tool catalogue: /.well-known/webmcp.json - Site guide: /llms.txt",
]

LLMS_OLD = (
    '    `- [MCP discovery](${SITE.url}/.well-known/mcp.json): discovery document for the MCP server`,\n'
    '    ""\n'
    '  );\n'
    '  return lines.join("\\n");\n'
    '}\n'
    '__name(buildLlms, "buildLlms");'
)

ROBOTS_OLD = (
    '  lines.push(`Sitemap: ${SITE.url}/sitemap.xml`, "");\n'
    '  return lines.join("\\n");\n'
    '}\n'
    '__name(buildRobots, "buildRobots");'
)

RETURN_LINE = '  return lines.join("\\n");'


def js_push(lines):
    body = ",\n".join("    " + json.dumps(x) for x in lines)
    return "  lines.push(\n" + body + "\n  );\n"


def apply(src: str) -> str:
    # Input guards: this transform is defined against the shipped
    # (post-patch_ot.py) bundle only. Anything else - stop.
    assert 'rel="webmcp"' not in src, "already patched: webmcp link present"
    assert "## WebMCP tools" not in src, "already patched: llms section present"
    assert 'app.post("/api/webmcp-beacon"' in src, "input is not the shipped bundle: beacon route missing"
    metas = META_RE.findall(src)
    assert len(metas) == 5, f"expected 5 origin-trial metas, found {len(metas)}"
    assert len(set(metas)) == 1, "origin-trial metas differ across pages"
    assert src.count(LLMS_OLD) == 1, "buildLlms anchor not found exactly once"
    assert src.count(ROBOTS_OLD) == 1, "buildRobots anchor not found exactly once"

    expected = 0

    # 1. Head link immediately after each origin-trial meta.
    insert = "\n    " + LINK
    out = META_RE.sub(lambda m: m.group(0) + insert, src)
    expected += 5 * len(insert)

    # 2. "## WebMCP tools" section appended to buildLlms's output.
    llms_lines = ["## WebMCP tools", "", LLMS_INSTRUCTION, ""] + [
        "- `" + name + "` — " + desc for name, desc in TOOLS
    ] + [""]
    llms_new = LLMS_OLD.replace(RETURN_LINE, js_push(llms_lines) + RETURN_LINE)
    assert llms_new != LLMS_OLD and out.count(LLMS_OLD) == 1
    out = out.replace(LLMS_OLD, llms_new)
    expected += len(llms_new) - len(LLMS_OLD)

    # 3. Canonical comment block appended to buildRobots's output.
    robots_new = ROBOTS_OLD.replace(RETURN_LINE, js_push(ROBOTS_BLOCK + [""]) + RETURN_LINE)
    assert robots_new != ROBOTS_OLD and out.count(ROBOTS_OLD) == 1
    out = out.replace(ROBOTS_OLD, robots_new)
    expected += len(robots_new) - len(ROBOTS_OLD)

    assert out.count(LINK) == 5, "webmcp link must land on all 5 pages"
    assert out.count('"## WebMCP tools"') == 1, "llms section must land exactly once"
    for line in ROBOTS_BLOCK:
        assert out.count(json.dumps(line)) == 1, "robots block line missing: " + line
    assert len(out) - len(src) == expected, (
        "delta must be exactly the advertisement insertions "
        f"({len(out) - len(src)} != {expected})"
    )
    return out


def main(argv):
    args = [a for a in argv[1:] if a != "-i"]
    inplace = "-i" in argv
    if len(args) != 1:
        print(__doc__)
        return 2
    path = args[0]
    with open(path, encoding="utf-8") as f:
        src = f.read()
    out = apply(src)
    if inplace:
        with open(path, "w", encoding="utf-8") as f:
            f.write(out)
        print(f"patched in place: {path} ({len(src)} -> {len(out)} chars)", file=sys.stderr)
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
